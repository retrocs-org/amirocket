#!/usr/bin/env python3
"""Generate native Installer/Shell scripts from the single runtime inventory."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def render(qa=False,uninstall=False):
    inventory=json.loads((ROOT/'installer/runtime.json').read_text())
    names=sorted(inventory)
    lines=['; Generated by scripts/make-installer.py; SPDX-License-Identifier: GPL-3.0-or-later',
      '(set @app-name "AmiRocket")','(set #helper (expandpath "CreateIcons"))',
      '(if (< (/ (getversion "workbench.library" (resident)) 65536) 47) (abort "AmiRocket requires AmigaOS 3.2 or newer."))',
      '(if (<> (run (cat "\\\"" #helper "\\\" CHECK")) 0) (abort "Close AmiRocket clients, Preferences and monitors before installation."))']
    if qa:
        lines+=['(user 0)','(set #dest "RAM:AmiRocketInstallerQA/AmiRocket")',f'(set #action {1 if uninstall else 0})','(set #startup 0)']
    else:
        lines+=['(welcome "Install, update or uninstall AmiRocket. Updates preserve settings and custom plugins.")',
          '(user 1)','(set #action (askchoice (prompt "AmiRocket installation") (help "Install/update preserves ENVARC:AmiRocket.prefs. Uninstall removes only managed files and keeps settings.") (choices "Install / update" "Uninstall (keep settings)") (default 0)))',
          '(set #parent (askdir (prompt "Choose the parent drawer containing AmiRocket") (help "AmiRocket and AmiRocketPrefs stay together in one drawer.") (default "SYS:Utilities")))',
          '(set #dest (tackon #parent "AmiRocket"))','(user 0)','(set #startup 0)']
    lines+=['(if (= #action 0) (', '(if (= (exists #dest (noreq)) 0) (makedir #dest))']
    for directory in sorted({str(Path(n).parent) for n in names if str(Path(n).parent)!='.'}):
        lines.append('(if (= (exists (tackon #dest "'+directory+'") (noreq)) 0) (makedir (tackon #dest "'+directory+'")))')
    for n in names:
        target=str(Path(n).parent)
        body='(copyfiles (source "'+n+'") (dest '+('#dest' if target=='.' else '(tackon #dest "'+target+'")')+') (help "Copy verified release files") (nogauge))'
        if n.endswith('.info'):body='(if (= (exists (tackon #dest "'+n+'") (noreq)) 0) '+body+')'
        lines.append(body)
    if not qa:
        lines+=['(user 1)','(set #startup (askbool (prompt "Start AmiRocket automatically with Workbench?") (help "Existing per-server auto-connect settings apply. No account settings are changed.") (choices "Yes" "No") (default 0)))']
    lines+=['(if (= #startup 1)', '(if (<> (run (cat "\\\"" #helper "\\\" \\\"" #dest "\\\" STARTUP")) 0) (abort "Files installed; could not create the Workbench startup icon."))',
      '(if (<> (run (cat "\\\"" #helper "\\\" \\\"" #dest "\\\" NOSTARTUP")) 0) (abort "Files installed; could not create missing icons.")))', ') (',
      '(if (= (exists (tackon #dest "AmiRocket") (noreq)) 0) (abort "This is not an AmiRocket installation. Nothing removed."))']
    if not qa:lines+=['(user 1)','(if (= (askbool (prompt "Remove managed AmiRocket files? Settings, custom plugins and unrelated files are kept.") (help "This does not delete ENVARC:AmiRocket.prefs.") (choices "Remove" "Cancel") (default 0)) 0) (exit "Nothing removed" (quiet)))']
    lines+=['(if (<> (run (cat "\\\"" #helper "\\\" \\\"" #dest "\\\" REMOVE-STARTUP")) 0) (abort "Could not remove the owned startup entry."))'] if not qa else []
    for n in names:
        lines.append('(if (= (exists (tackon #dest "'+n+'") (noreq)) 1) (delete (tackon #dest "'+n+'")))')
    lines+=['))','(exit "AmiRocket operation completed. Settings preserved." (quiet))']
    return '\n'.join(lines)+'\n'
def shell():
    names=sorted(json.loads((ROOT/'installer/runtime.json').read_text()))
    lines=['.key DEST/A','.bra {','.ket }','; Install into the full destination drawer; settings are never copied.',
           'FailAt 10','"CreateIcons" CHECK','If WARN',' Echo "Close AmiRocket before installation."',' Quit 10','EndIf',
           'FailAt 5','If NOT EXISTS "{DEST}"',' MakeDir "{DEST}"','EndIf']
    for directory in sorted({str(Path(n).parent) for n in names if str(Path(n).parent)!='.'}):lines+=['If NOT EXISTS "{DEST}/'+directory+'"',' MakeDir "{DEST}/'+directory+'"','EndIf']
    for n in names:
        cmd='Copy "'+n+'" TO "{DEST}/'+n+'" CLONE'
        if n.endswith('.info'):lines+=['If NOT EXISTS "{DEST}/'+n+'"', ' '+cmd,'EndIf']
        else:lines.append(cmd)
    lines+=['"CreateIcons" "{DEST}" NOSTARTUP','Echo "AmiRocket installed. Settings preserved."']
    return '\n'.join(lines)+'\n'
if __name__=='__main__':
    (ROOT/'installer/Install').write_text(render(),encoding='ascii')
    (ROOT/'installer/Install-AmiRocket').write_text(shell(),encoding='ascii')
