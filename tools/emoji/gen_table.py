#!/usr/bin/env python3
"""Writes src/core/emoji_table.c from emoji_list.py."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from emoji_list import EMOJI

out = sys.argv[1]
lines = ["/* Generated by tools/emoji/gen_table.py - do not edit. */",
         '#include "emoji.h"', "",
         "const EmojiInfo emoji_table[] = {"]
for i, (code, cp, fb, _) in enumerate(EMOJI):
    fbc = fb.replace("\\", "\\\\")
    lines.append(f'    {{ 0x{cp:X}UL, "{code}", "{fbc}" }},   /* {i} */')
lines += ["};", f"const int emoji_count = {len(EMOJI)};", "",
          "const EmojiAlias emoji_aliases[] = {"]
for i, (code, cp, fb, al) in enumerate(EMOJI):
    for a in al:
        lines.append(f'    {{ "{a}", {i} }},')
lines += ["    { 0, 0 }", "};", ""]
open(out, "w").write("\n".join(lines))
